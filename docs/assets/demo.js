/* Interactive replay of real scanner output. Every value shown here comes from
   docs/assets/fixtures.mjs, generated by scripts/build_site_fixtures.py. */
import { fixtures } from "./fixtures.mjs";
import {
  GROUPS,
  groupFixtures,
  findFixture,
  filterFindings,
  severityCounts,
  cliGate,
  scoreTone,
  sourceLines,
  formatCell,
  fixtureMeta,
} from "./demo-engine.mjs";

const CONFIDENCE_BASIS_LABELS = {
  calibrated_probability: "uncalibrated ranking score",
  heuristic_weight: "heuristic rule strength",
  unavailable: "unavailable",
};
const confidenceLabel = (basis) => CONFIDENCE_BASIS_LABELS[basis] || "unavailable";

const root = document.querySelector("[data-demo]");
if (root) {
  const groupTabs = root.querySelector("[data-group-tabs]");
  const fixtureList = root.querySelector("[data-fixture-list]");
  const output = root.querySelector("[data-output]");
  const head = root.querySelector("[data-output-head]");
  const body = root.querySelector("[data-output-body]");
  const overlay = root.querySelector("[data-overlay]");
  const status = root.querySelector("[data-demo-status]");
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  const groups = groupFixtures(fixtures);
  const all = groups.flatMap((group) => group.fixtures);

  const state = {
    group: groups[0]?.id || "code",
    fixture: null,
    severity: "all",
    scanning: false,
  };

  const stored = decodeURIComponent(window.location.hash.replace(/^#/, ""));
  if (stored && findFixture(fixtures, stored)) {
    const match = findFixture(fixtures, stored);
    state.group = match.group;
    state.fixture = match.id;
  } else {
    state.fixture = groups[0]?.fixtures[0]?.id || null;
  }

  const el = (tag, attrs = {}, ...children) => {
    const node = document.createElement(tag);
    for (const [key, value] of Object.entries(attrs)) {
      if (value === null || value === undefined || value === false) continue;
      if (key === "class") node.className = value;
      else if (key === "text") node.textContent = value;
      else if (key === "dataset") Object.assign(node.dataset, value);
      else if (key.startsWith("on") && typeof value === "function") {
        node.addEventListener(key.slice(2), value);
      } else node.setAttribute(key, value === true ? "" : String(value));
    }
    for (const child of children.flat()) {
      if (child === null || child === undefined || child === false) continue;
      node.append(child.nodeType ? child : document.createTextNode(String(child)));
    }
    return node;
  };

  const announce = (message) => {
    if (!status) return;
    status.textContent = "";
    window.setTimeout(() => {
      status.textContent = message;
    }, 30);
  };

  const severityClass = (severity) => `badge-${severity}`;

  const countText = (counts) =>
    `${counts.high} high · ${counts.medium} medium · ${counts.low} low`;

  const activeFixture = () => findFixture(fixtures, state.fixture);
  const activeGroup = () => groups.find((group) => group.id === state.group) || groups[0];

  /* --- Tabs ------------------------------------------------------------- */
  const renderTabs = () => {
    groupTabs.replaceChildren();
    for (const [index, group] of groups.entries()) {
      const count = group.fixtures.length;
      const button = el(
        "button",
        {
          type: "button",
          role: "tab",
          id: `group-tab-${group.id}`,
          "aria-selected": String(group.id === state.group),
          "aria-controls": "fixture-list",
          tabindex: group.id === state.group ? "0" : "-1",
          onclick: () => selectGroup(group.id),
          onkeydown: (event) => {
            if (!["ArrowLeft", "ArrowRight", "Home", "End"].includes(event.key)) return;
            event.preventDefault();
            const next =
              event.key === "Home"
                ? 0
                : event.key === "End"
                  ? groups.length - 1
                  : (index + (event.key === "ArrowRight" ? 1 : -1) + groups.length) % groups.length;
            const target = groups[next];
            selectGroup(target.id);
            groupTabs.querySelector(`#group-tab-${target.id}`)?.focus();
          },
        },
        el("span", { text: group.label }),
        el("span", { class: "tab-count", text: ` · ${count}` })
      );
      groupTabs.append(button);
    }
  };

  /* --- Fixture list ----------------------------------------------------- */
  const renderList = () => {
    const group = activeGroup();
    fixtureList.replaceChildren();
    if (!group || !group.fixtures.length) {
      fixtureList.append(el("li", { class: "f-empty", text: "No fixtures in this group." }));
      return;
    }
    for (const fixture of group.fixtures) {
      const counts = severityCounts(fixture.findings);
      const marker = fixture.clean
        ? el("span", { class: "badge badge-safe", text: "clean" })
        : el("span", {
            class: `badge ${counts.high ? "badge-high" : "badge-medium"}`,
            text: fixture.trustScore != null ? `${fixture.trustScore}/100` : `${counts.total} found`,
          });
      fixtureList.append(
        el(
          "li",
          {},
          el(
            "button",
            {
              type: "button",
              "aria-pressed": String(fixture.id === state.fixture),
              onclick: () => selectFixture(fixture.id),
            },
            el("span", { class: "f-name", text: fixture.name }, marker),
            el("span", { class: "f-desc", text: fixture.title })
          )
        )
      );
    }
  };

  /* --- Head ------------------------------------------------------------- */
  const renderHead = (fixture) => {
    const meta = fixtureMeta(fixture);
    head.replaceChildren(
      el(
        "div",
        { class: "head-main" },
        el("h2", { id: "demo-title", text: fixture.title }),
        el("p", { text: fixture.description })
      ),
      el(
        "div",
        { class: "head-actions" },
        el("span", {
          class: "badge",
          text: `${fixture.group} · prerecorded`,
        }),
        el("button", {
          type: "button",
          class: "button button-small button-secondary",
          text: "Replay output",
          onclick: replay,
        }),
        el("button", {
          type: "button",
          class: "copy-button",
          "data-copy": fixture.command,
          text: "Copy command",
        })
      ),
      fixture.clean
        ? el("span", { class: "badge badge-safe", text: "no findings" })
        : el("span", {
            class: `badge ${meta.counts.high ? "badge-high" : "badge-medium"}`,
            text: `${meta.counts.total} finding${meta.counts.total === 1 ? "" : "s"}`,
          })
    );
    output.setAttribute("aria-labelledby", "demo-title");
  };

  /* --- Score / gate row ------------------------------------------------- */
  const renderGate = (fixture) => {
    const meta = fixtureMeta(fixture);
    const gate = meta.gate;
    if (meta.hasScore) {
      const tone = scoreTone(fixture.trustScore);
      const color =
        tone === "safe" ? "var(--safe)" : tone === "warn" ? "var(--warn)" : "var(--danger)";
      return el(
        "div",
        { class: "score-row" },
        el(
          "div",
          {
            class: "score-ring",
            style: `--score:${fixture.trustScore};--ring-color:${color}`,
            role: "img",
            "aria-label": `Trust score ${fixture.trustScore} out of 100`,
          },
          el("span", { text: String(fixture.trustScore) }),
          el("small", { text: "/100" })
        ),
        el(
          "div",
          { class: "score-meta" },
          el("strong", { text: `${meta.word} · ${gate.label}` }),
          el("span", { text: gate.detail }),
          el("span", { text: `Score rule: 100 − 35·high − 15·medium − 5·low` })
        )
      );
    }
    return el(
      "div",
      { class: "score-row" },
      el("span", {
        class: `gate-pill ${gate.failing ? "is-failing" : "is-passing"}`,
        text: gate.label,
      }),
      el(
        "div",
        { class: "score-meta" },
        el("strong", {
          text: gate.failing ? "CLI gate fails" : "CLI gate passes",
        }),
        el("span", { text: gate.detail }),
        el("span", { text: "Code scans report findings; trust scores apply to datasets." })
      )
    );
  };

  /* --- Findings --------------------------------------------------------- */
  const renderFindings = (fixture) => {
    const panel = el("div", { class: "finding-panel" });
    const counts = severityCounts(fixture.findings);
    const chips = el("div", {
      class: "demo-filters",
      role: "group",
      "aria-label": "Filter findings by severity",
    });
    const options = [
      { id: "all", label: `All ${counts.total}` },
      { id: "high", label: `High ${counts.high}` },
      { id: "medium", label: `Medium ${counts.medium}` },
      { id: "low", label: `Low ${counts.low}` },
    ];
    for (const option of options) {
      chips.append(
        el("button", {
          type: "button",
          class: "chip",
          text: option.label,
          "aria-pressed": String(state.severity === option.id),
          disabled: option.id !== "all" && counts[option.id] === 0,
          onclick: () => {
            state.severity = option.id;
            renderBody();
            announce(
              option.id === "all"
                ? "Showing all findings"
                : `Showing ${option.id} findings only`
            );
          },
        })
      );
    }
    panel.append(chips);

    const list = el("div", { class: "finding-list" });
    const visible = filterFindings(fixture.findings, state.severity);
    if (!visible.length) {
      const message = fixture.clean
        ? "No findings. The default CLI gate exits 0 for this fixture."
        : `No ${state.severity} findings in this fixture.`;
      list.append(el("p", { class: "empty-state", text: message }));
    } else {
      for (const finding of visible) {
        const column =
          finding.column === "*"
            ? "train/test split"
            : fixture.group === "code"
              ? String(finding.column || "file").split(":")[0]
              : finding.column || "table";
        const item = el(
          "details",
          { class: `finding ${finding.severity}` },
          el(
            "summary",
            {},
            el("span", { class: `badge ${severityClass(finding.severity)}`, text: finding.severity }),
            el("span", { class: "f-kind", text: finding.kind }),
            el("span", { class: "f-col", text: column }),
            Number.isInteger(finding.line)
              ? el("span", { class: "f-col", text: `line ${finding.line}` })
              : null
          ),
          el(
            "div",
            { class: "finding-body" },
            el("p", { text: finding.detail }),
            finding.fix
              ? el("div", { class: "fix" }, el("strong", { text: "Fix: " }), finding.fix)
              : null
          )
        );
        item.addEventListener("toggle", () => {
          if (item.open && Number.isInteger(finding.line)) focusLine(finding.line);
        });
        list.append(item);
      }
    }
    panel.append(list);

    panel.append(
      el(
        "div",
        { class: "demo-command" },
        el("code", { text: `$ ${fixture.command}` }),
        el("button", {
          type: "button",
          class: "copy-button",
          "data-copy": fixture.command,
          text: "Copy",
        })
      )
    );
    return panel;
  };

  const focusLine = (number) => {
    const line = body.querySelector(`[data-line="${number}"]`);
    if (!line) return;
    line.classList.add("is-target");
    window.setTimeout(() => line.classList.remove("is-target"), 1400);
    const scroller = line.closest(".source-view");
    if (!scroller) return;
    const lineRect = line.getBoundingClientRect();
    const viewRect = scroller.getBoundingClientRect();
    const top =
      scroller.scrollTop + (lineRect.top - viewRect.top) - viewRect.height / 2 + lineRect.height / 2;
    scroller.scrollTo({
      top: Math.max(0, top),
      behavior: reduceMotion.matches ? "auto" : "smooth",
    });
  };

  /* --- Side panels ------------------------------------------------------ */
  const panel = (title, ...content) =>
    el("div", { class: "demo-side-panel" }, el("h3", { text: title }), ...content);

  const sourcePanel = (fixture) => {
    const lines = sourceLines(fixture);
    const view = el("div", { class: "source-view", tabindex: "0", "aria-label": `Source of ${fixture.name}` });
    for (const line of lines) {
      view.append(
        el(
          "div",
          {
            class: `source-line${line.marked ? ` hit ${line.severity}` : ""}`,
            dataset: { line: String(line.number) },
          },
          el("span", { class: "ln", text: String(line.number) }),
          el("span", { class: "code", text: line.text || " " })
        )
      );
    }
    return [panel(`Source · ${fixture.name}`, view)];
  };

  const previewPanel = (fixture) => {
    const table = el("table", { class: "preview-table" });
    const thead = el("thead");
    const headRow = el("tr");
    for (const column of fixture.columns || []) headRow.append(el("th", { scope: "col", text: column }));
    thead.append(headRow);
    const tbody = el("tbody");
    for (const row of fixture.preview || []) {
      const tr = el("tr");
      for (const column of fixture.columns || []) {
        tr.append(el("td", { text: formatCell(row[column]) }));
      }
      tbody.append(tr);
    }
    table.append(thead, tbody);
    return [
      panel(
        `Preview · ${(fixture.preview || []).length} of ${fixture.rows || 0} rows`,
        el("div", { class: "table-scroll" }, table)
      ),
    ];
  };

  const metaPanel = (fixture) => {
    const meta = fixtureMeta(fixture);
    const rows = [];
    if (meta.target) rows.push(["target", meta.target]);
    if (meta.rows) rows.push(["rows", String(meta.rows)]);
    if (meta.columns.length) rows.push(["columns", String(meta.columns.length)]);
    if (meta.check) rows.push(["check", meta.check]);
    if (meta.split) rows.push(["split", `${meta.split.train} train / ${meta.split.test} test`]);
    if (meta.duplicates != null) rows.push(["duplicated test rows", String(meta.duplicates)]);
    const list = el("dl", { class: "meta-list" });
    for (const [key, value] of rows) {
      list.append(el("dt", { text: key }), el("dd", { text: value }));
    }
    return [panel("Audit inputs", list)];
  };

  /* --- Experimental AI output (opt-in layer, prerecorded) ---------------- */
  const aiPanel = (fixture) => {
    const ai = fixture.ai;
    if (!ai) return [];
    const wrapper = el("div", { class: "demo-side-panel ai-panel" });
    wrapper.append(
      el("h3", { text: "Experimental AI · prerecorded" }),
      el("p", {
        class: "ai-meta",
        text: `${ai.model.name} · ${ai.model.version} · threshold ${ai.model.threshold}`,
      }),
      el("p", {
        class: "ai-meta",
        text: "Unverified hypotheses only. They never change deterministic findings, severity or the trust score.",
      })
    );

    if (!ai.hypotheses.length) {
      wrapper.append(
        el("p", {
          class: "empty-state",
          text: "No AI hypothesis for this fixture. A clean pass is not proof of safety.",
        })
      );
    } else {
      const list = el("ul", { class: "ai-list" });
      for (const hypothesis of ai.hypotheses) {
        const item = el(
          "li",
          { class: "ai-item" },
          el(
            "div",
            { class: "ai-title" },
            el("span", {
              class: `badge badge-${hypothesis.severityHint}`,
              text: hypothesis.severityHint,
            }),
            el("span", { text: hypothesis.title })
          ),
          el("p", {
            class: "ai-meta",
            text: `confidence (${confidenceLabel(hypothesis.confidenceBasis)}) ${hypothesis.confidence.toFixed(2)} · ${hypothesis.concept} · ${hypothesis.location}`,
          }),
          el("p", { text: hypothesis.explanation })
        );
        const evidence = el(
          "details",
          { class: "ai-evidence" },
          el("summary", { text: `Evidence (${hypothesis.evidence.length})` })
        );
        const evidenceList = el("ul");
        for (const span of hypothesis.evidence) {
          evidenceList.append(
            el(
              "li",
              {},
              el("span", {
                class: "ai-meta",
                text: `${span.source}/${span.kind} · ${span.location}`,
              }),
              el("code", { text: span.excerpt })
            )
          );
        }
        evidence.append(evidenceList);
        item.append(evidence);
        list.append(item);
      }
      wrapper.append(list);
    }

    if (ai.remediation.length) {
      const remediation = el(
        "details",
        { class: "ai-remediation" },
        el("summary", { text: `Remediation plan (${ai.remediation.length})` })
      );
      const causes = el("ol");
      for (const cause of ai.remediation) {
        const actions = el("ul");
        for (const action of cause.actions) actions.append(el("li", { text: action }));
        causes.append(el("li", {}, el("strong", { text: cause.title }), actions));
      }
      remediation.append(causes);
      wrapper.append(remediation);
    }

    return [wrapper];
  };

  const renderBody = () => {
    const fixture = activeFixture();
    if (!fixture) {
      body.replaceChildren(el("p", { class: "empty-state", text: "Select a recorded example." }));
      return;
    }
    const results = el("div", { class: "demo-results" }, renderGate(fixture), renderFindings(fixture));
    let side = [];
    if (fixture.group === "code") side = [...sourcePanel(fixture), ...aiPanel(fixture)];
    else side = [...previewPanel(fixture), ...metaPanel(fixture)];
    if (fixture.group === "overlap") {
      side = [...metaPanel(fixture), ...previewPanel(fixture)];
    }
    body.replaceChildren(results, el("div", { class: "demo-side-info" }, ...side));
  };

  /* --- Selection and replay --------------------------------------------- */
  const selectGroup = (id) => {
    const group = groups.find((item) => item.id === id);
    if (!group) return;
    state.group = id;
    state.severity = "all";
    state.fixture = group.fixtures[0]?.id || null;
    renderTabs();
    renderList();
    renderAll();
  };

  const selectFixture = (id) => {
    const fixture = findFixture(fixtures, id);
    if (!fixture) return;
    state.group = fixture.group;
    state.fixture = id;
    state.severity = "all";
    renderTabs();
    renderList();
    renderAll();
  };

  const updateHash = () => {
    if (state.fixture) window.history.replaceState(null, "", `#${state.fixture}`);
  };

  const renderAll = () => {
    const fixture = activeFixture();
    if (fixture) {
      renderHead(fixture);
      renderBody();
      updateHash();
      root.dataset.activeGroup = state.group;
      root.dataset.activeFixture = state.fixture;
    }
  };

  const replay = () => {
    if (state.scanning) return;
    state.scanning = true;
    output.classList.add("is-scanning");
    const fixture = activeFixture();
    if (overlay) {
      overlay.querySelector("[data-overlay-name]").textContent = fixture?.name || "fixture";
    }
    announce("Replaying the recorded scanner output");
    const delay = reduceMotion.matches ? 80 : 480;
    window.setTimeout(() => {
      state.severity = "all";
      renderAll();
      output.classList.remove("is-scanning");
      state.scanning = false;
      announce(`Replayed ${fixture?.name || "fixture"}; no scanning happened in the browser`);
    }, delay);
  };

  window.addEventListener("hashchange", () => {
    const id = decodeURIComponent(window.location.hash.replace(/^#/, ""));
    if (id && findFixture(fixtures, id) && id !== state.fixture) selectFixture(id);
  });

  renderTabs();
  renderList();
  renderAll();
}
