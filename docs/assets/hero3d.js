/* Dependency-free 3-D field for real rows from the checked-in split fixture.
   The points come from docs/assets/fixtures.mjs (generated by the Python
   scanner build step); nothing here invents data. */
import { fixtures } from "./fixtures.mjs";

const canvas = document.getElementById("leak-canvas");
if (canvas) {
  const fixture = fixtures.overlaps.find((item) => item.id === "overlap_exact");
  const plot = fixture?.plot;
  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  const toggle = document.querySelector("[data-dup-toggle]");
  const readout = document.querySelector("[data-dup-readout]");
  const ctx = canvas.getContext("2d");

  let width = 0;
  let height = 0;
  let dpr = 1;
  let rotY = -0.62;
  let rotX = 0.42;
  let dragging = false;
  let moved = false;
  let lastX = 0;
  let lastY = 0;
  let showDuplicates = true;
  let active = true;
  let frame = 0;

  const state = {
    train: (plot?.train || []).map((p) => ({ ...p, source: "train" })),
    test: (plot?.test || []).map((p) => ({ ...p, source: "test" })),
    links: [],
    duplicates: plot?.counts?.duplicates ?? 0,
  };

  for (const point of state.test) {
    if (point.pair !== null && point.pair !== undefined) {
      const partner = state.train[point.pair];
      if (partner) state.links.push([point, partner]);
    }
  }

  const resize = () => {
    const rect = canvas.getBoundingClientRect();
    dpr = Math.min(window.devicePixelRatio || 1, 2);
    width = Math.max(1, Math.round(rect.width));
    height = Math.max(1, Math.round(rect.height));
    canvas.width = Math.round(width * dpr);
    canvas.height = Math.round(height * dpr);
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    draw();
  };

  const rotate = (point) => {
    const x = point.x - 0.5;
    const y = point.y - 0.5;
    const z = point.z - 0.5;
    const cosY = Math.cos(rotY);
    const sinY = Math.sin(rotY);
    const cosX = Math.cos(rotX);
    const sinX = Math.sin(rotX);
    const rx = x * cosY - z * sinY;
    const rz = x * sinY + z * cosY;
    const ry = y * cosX - rz * sinX;
    const rz2 = y * sinX + rz * cosX;
    return { x: rx, y: ry, z: rz2 };
  };

  const project = (point) => {
    const p = rotate(point);
    const distance = 3.4;
    const scale = Math.min(width, height) * 0.95;
    const depth = distance / (distance - p.z * 0.85);
    return {
      x: width / 2 + p.x * scale * depth,
      y: height / 2 + p.y * scale * depth,
      depth,
    };
  };

  const box = () => {
    const corners = [];
    for (const x of [0, 1]) {
      for (const y of [0, 1]) {
        for (const z of [0, 1]) {
          corners.push(project({ x, y, z }));
        }
      }
    }
    return corners;
  };

  const grid = () => {
    ctx.save();
    ctx.strokeStyle = "rgba(133, 171, 209, 0.13)";
    ctx.lineWidth = 1;
    const steps = 5;
    for (let i = 0; i <= steps; i += 1) {
      const t = i / steps;
      const a = project({ x: t, y: 0, z: 0 });
      const b = project({ x: t, y: 0, z: 1 });
      const c = project({ x: 0, y: 0, z: t });
      const d = project({ x: 1, y: 0, z: t });
      ctx.beginPath();
      ctx.moveTo(a.x, a.y);
      ctx.lineTo(b.x, b.y);
      ctx.moveTo(c.x, c.y);
      ctx.lineTo(d.x, d.y);
      ctx.stroke();
    }
    ctx.restore();
  };

  const drawAxes = () => {
    const origin = project({ x: 0, y: 0, z: 0 });
    const axes = [
      { point: { x: 1, y: 0, z: 0 }, color: "#5eead4", label: "log amount" },
      { point: { x: 0, y: 1, z: 0 }, color: "#f7c65a", label: "hour" },
      { point: { x: 0, y: 0, z: 1 }, color: "#8ab4ff", label: "distance" },
    ];
    ctx.save();
    ctx.font = "10px 'Cascadia Code', Consolas, monospace";
    for (const axis of axes) {
      const end = project(axis.point);
      ctx.strokeStyle = axis.color;
      ctx.globalAlpha = 0.55;
      ctx.beginPath();
      ctx.moveTo(origin.x, origin.y);
      ctx.lineTo(end.x, end.y);
      ctx.stroke();
      ctx.globalAlpha = 0.9;
      ctx.fillStyle = axis.color;
      ctx.fillText(axis.label, end.x + 4, end.y - 3);
    }
    ctx.restore();
  };

  const dot = (screen, radius, color, alpha = 1, glow = 0) => {
    ctx.save();
    ctx.globalAlpha = alpha;
    ctx.fillStyle = color;
    if (glow) {
      ctx.shadowColor = color;
      ctx.shadowBlur = glow;
    }
    ctx.beginPath();
    ctx.arc(screen.x, screen.y, radius, 0, Math.PI * 2);
    ctx.fill();
    ctx.restore();
  };

  const draw = () => {
    if (!ctx || !plot) return;
    ctx.clearRect(0, 0, width, height);

    const glow = ctx.createRadialGradient(
      width * 0.58,
      height * 0.42,
      10,
      width * 0.58,
      height * 0.42,
      Math.max(width, height) * 0.62
    );
    glow.addColorStop(0, "rgba(94, 234, 212, 0.09)");
    glow.addColorStop(1, "rgba(5, 10, 17, 0)");
    ctx.fillStyle = glow;
    ctx.fillRect(0, 0, width, height);

    grid();
    drawAxes();

    const trainPoints = state.train.map((p) => ({ point: p, screen: project(p) }));
    const testPoints = state.test.map((p) => ({ point: p, screen: project(p) }));

    if (showDuplicates) {
      ctx.save();
      ctx.lineWidth = 1;
      ctx.globalAlpha = 0.4;
      ctx.strokeStyle = "#ff7f7f";
      for (const [testPoint, trainPoint] of state.links) {
        const a = project(testPoint);
        const b = project(trainPoint);
        ctx.beginPath();
        ctx.moveTo(a.x, a.y);
        ctx.lineTo(b.x, b.y);
        ctx.stroke();
      }
      ctx.restore();
    }

    const layers = [
      ...trainPoints.map((item) => ({ ...item, kind: "train" })),
      ...testPoints.map((item) => ({ ...item, kind: "test" })),
    ].sort((a, b) => a.screen.depth - b.screen.depth);

    for (const item of layers) {
      const duplicated = item.point.dup && showDuplicates;
      if (item.kind === "train") {
        dot(item.screen, duplicated ? 3.4 : 2.2, duplicated ? "#ff7f7f" : "#5b7fa6", duplicated ? 0.95 : 0.55);
      } else if (duplicated) {
        dot(item.screen, 4.2, "#ff7f7f", 1, 14);
      } else {
        dot(item.screen, 2.6, "#f7c65a", 0.8);
      }
    }

    if (!showDuplicates) {
      ctx.save();
      ctx.fillStyle = "rgba(154, 173, 194, 0.85)";
      ctx.font = "11px 'Cascadia Code', Consolas, monospace";
      ctx.fillText("duplicates hidden", 14, height - 16);
      ctx.restore();
    }
  };

  const tick = () => {
    frame = window.requestAnimationFrame(tick);
    if (reduceMotion.matches || !active || dragging) return;
    rotY += 0.0014;
    draw();
  };

  const setDuplicates = (next) => {
    showDuplicates = next;
    if (toggle) {
      toggle.setAttribute("aria-pressed", String(next));
      toggle.textContent = next ? "Hide duplicates" : "Show duplicates";
    }
    if (readout) {
      readout.textContent = next
        ? `${state.duplicates} duplicated test rows highlighted`
        : `${state.duplicates} duplicated test rows hidden`;
    }
    draw();
  };

  if (toggle) {
    toggle.addEventListener("click", () => setDuplicates(!showDuplicates));
  }

  canvas.addEventListener("pointerdown", (event) => {
    dragging = true;
    moved = false;
    lastX = event.clientX;
    lastY = event.clientY;
    canvas.setPointerCapture(event.pointerId);
  });

  canvas.addEventListener("pointermove", (event) => {
    if (!dragging) return;
    const dx = event.clientX - lastX;
    const dy = event.clientY - lastY;
    if (Math.abs(dx) + Math.abs(dy) > 2) moved = true;
    lastX = event.clientX;
    lastY = event.clientY;
    rotY += dx * 0.006;
    rotX = Math.max(-1.15, Math.min(1.15, rotX + dy * 0.005));
    draw();
  });

  const release = () => {
    dragging = false;
  };
  canvas.addEventListener("pointerup", release);
  canvas.addEventListener("pointercancel", release);

  canvas.addEventListener("keydown", (event) => {
    const step = 0.12;
    if (event.key === "ArrowLeft") rotY -= step;
    else if (event.key === "ArrowRight") rotY += step;
    else if (event.key === "ArrowUp") rotX = Math.max(-1.15, rotX - step);
    else if (event.key === "ArrowDown") rotX = Math.min(1.15, rotX + step);
    else return;
    event.preventDefault();
    draw();
  });

  if ("ResizeObserver" in window) {
    new ResizeObserver(resize).observe(canvas);
  } else {
    window.addEventListener("resize", resize);
  }

  if ("IntersectionObserver" in window) {
    new IntersectionObserver(
      (entries) => {
        active = entries.some((entry) => entry.isIntersecting);
      },
      { threshold: 0.02 }
    ).observe(canvas);
  }

  if (readout) {
    readout.textContent = `${state.duplicates} duplicated test rows highlighted`;
  }
  resize();
  if (!reduceMotion.matches) tick();
}
