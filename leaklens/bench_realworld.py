"""Phase 6 real-world evaluation and performance report.

Usage::

    python -m leaklens.bench_realworld
    python -m leaklens.bench_realworld --write docs/AI_REALWORLD.md \
        --performance docs/AI_PERFORMANCE.md

The benchmark applies the frozen model to the frozen real-world holdout in
``leaklens/ai/corpus_realworld.py`` exactly once per run.  It never tunes on the
result.  The authored Phase 5 locked test and the scanner-benchmark transfer set
are reported alongside it so authored, synthetic and public evidence stay
clearly separated.
"""

