def _table(rows):
    if not rows:
        return ""
    heads = list(rows[0])
    h = "".join(f"<th>{html.escape(str(k))}</th>" for k in heads)
    b = "".join(
        "<tr>"
        + "".join(f"<td>{html.escape(str(r.get(k, '')))}</td>" for k in heads)
        + "</tr>"
        for r in rows
    )
    return f"<table><tr>{h}</tr>{b}</table>"


def _intelligence_section(data: dict) -> str:
    """Render optional intelligence data while escaping all untrusted text."""
    confidence = data.get("confidence", {})
    level = html.escape(str(confidence.get("level", "unknown")))
    try:
        score_text = f"{float(confidence.get('score', 0)):.2f}"
    except (TypeError, ValueError):
        score_text = "unavailable"

    reasons = "".join(
        f"<li>{html.escape(str(reason))}</li>"
        for reason in confidence.get("reasons", [])
    )
    sections = [
        "<h2>Intelligence analysis</h2>",
        '<div class="card">',
        f"<p><b>Confidence:</b> {level} ({score_text})</p>",
        f"<ul>{reasons}</ul>" if reasons else "",
        "</div>",
    ]

    clusters = data.get("clusters", [])
    if clusters:
        rows = []
        for cluster in clusters:
            local = cluster.get("confidence", {})
            try:
                local_score = f"{float(local.get('score', 0)):.2f}"
            except (TypeError, ValueError):
                local_score = "unavailable"
            rows.append(
                {
                    "Anchor": cluster.get("anchor", ""),
                    "Kind": cluster.get("anchor_kind", ""),
                    "Findings": ", ".join(cluster.get("finding_kinds", [])),
                    "Evidence": len(cluster.get("evidence_ids", [])),
                    "Confidence": f"{local.get('level', 'unknown')} ({local_score})",
                    "Priority": cluster.get("priority", ""),
                    "Measured impact": "; ".join(cluster.get("measured_impact", [])),
                }
            )
        sections.append(
            "<h2>Evidence clusters</h2>"
            '<div class="card"><p class="sub">Existing evidence grouped by '
            "feature, split or file. Clusters add no findings and keep every "
            "member traceable.</p>" + _table(rows) + "</div>"
        )

    links = data.get("links", [])
    if links:
        rows = [
            {
                "From": link.get("source_id", ""),
                "Relation": link.get("relation", ""),
                "To": link.get("target_id", ""),
                "Why": link.get("rationale", ""),
            }
            for link in links
        ]
        sections.append(
            "<h2>Evidence links</h2>"
            '<div class="card"><p class="sub">Directed relations between '
            "existing evidence records. Links add no findings.</p>"
            + _table(rows)
            + "</div>"
        )

    root_causes = data.get("root_causes", [])
    if root_causes:
        sections.append("<h2>Root-cause analysis</h2>")
        for cause in root_causes:
            title = html.escape(str(cause.get("title", "")))
            explanation = html.escape(str(cause.get("explanation", "")))
            category = html.escape(str(cause.get("category", "")))
            sections.append(
                f'<div class="card"><h3>{title}</h3>'
                f'<p class="sub">{category}</p><p>{explanation}</p></div>'
            )

    recommendations = data.get("recommendations", [])
    if recommendations:
        sections.append("<h2>Remediation recommendations</h2>")
        for item in recommendations:
            title = html.escape(str(item.get("title", "")))
            description = html.escape(str(item.get("description", "")))
            priority = html.escape(str(item.get("priority", "")))
            actions = "".join(
                f"<li>{html.escape(str(action))}</li>"
                for action in item.get("actions", [])
            )
            validation = "".join(
                f"<li>{html.escape(str(step))}</li>"
                for step in item.get("validation_steps", [])
            )
            sections.append(
                f'<div class="card"><h3>{title}</h3>'
                f"<p><b>Priority:</b> {priority}</p><p>{description}</p>"
                f"<b>Actions</b><ul>{actions}</ul>"
                f"<b>Validation</b><ul>{validation}</ul></div>"
            )

    return "".join(sections)


def _graph_baseline_section(data: dict) -> str:
    """Render the optional evidence-graph comparison with escaping."""
    if not data:
        return ""
    counts = data.get("counts", {})
    sections = [
        "<h2>Evidence-graph baseline comparison</h2>",
        '<div class="card">',
        f"<p><b>New:</b> {html.escape(str(counts.get('new', 0)))} · "
        f"<b>Unchanged:</b> {html.escape(str(counts.get('unchanged', 0)))} · "
        f"<b>Changed:</b> {html.escape(str(counts.get('changed', 0)))} · "
        f"<b>Resolved:</b> {html.escape(str(counts.get('resolved', 0)))} · "
        f"<b>Uncertain:</b> {html.escape(str(counts.get('uncertain', 0)))}</p>",
    ]
    if not data.get("resolution_complete", True):
        sections.append(
            '<p class="sub">One or both scans were incomplete or used a different '
            "analysis context, so missing evidence is shown as uncertain instead "
            "of resolved.</p>"
        )
    completeness = data.get("completeness") or {}
    for label in ("baseline", "current"):
        detail = completeness.get(label) or {}
        if detail.get("state") in (None, "complete"):
            continue
        reasons = "; ".join(str(reason) for reason in detail.get("reasons", []))
        sections.append(
            f"<p><b>{html.escape(label.capitalize())} scan completeness:</b> "
            f"{html.escape(str(detail.get('state', 'unknown')))}"
            + (f" ({html.escape(reasons)})" if reasons else "")
            + "</p>"
        )
    if data.get("duplicates"):
        sections.append(
            f"<p><b>Collapsed duplicate records:</b> "
            f"{html.escape(str(data.get('duplicates')))}</p>"
        )
    evidence = [
        item
        for item in data.get("evidence", [])
        if item.get("state") != "unchanged" or item.get("location_changed")
    ]
    if evidence:
        rows = [
            {
                "State": item.get("state", ""),
                "Kind": item.get("kind", ""),
                "Fingerprint": str(item.get("fingerprint") or "")[:12],
                "Evidence": item.get("current_id") or item.get("baseline_id") or "",
                "Location": (
                    f"{item.get('baseline_location') or 'unknown'} -> "
                    f"{item.get('current_location') or 'unknown'}"
                    if item.get("location_changed")
                    else ""
                ),
                "Changed": ", ".join(item.get("changes", [])),
            }
            for item in evidence
        ]
        sections.append(
            "<h3>Evidence changes</h3>"
            '<p class="sub">Evidence is matched by content rather than display '
            "location, so a finding that only moved lines is unchanged.</p>"
            + _table(rows)
        )
    clusters = [
        item
        for item in data.get("cluster_changes", [])
        if item.get("state") != "unchanged"
    ]
    if clusters:
        sections.append(
            "<h3>Cluster changes</h3>"
            + _table(
                [
                    {
                        "State": item.get("state", ""),
                        "Anchor": item.get("anchor", ""),
                        "Changed": ", ".join(item.get("changes", [])),
                    }
                    for item in clusters
                ]
            )
        )
    relationships = data.get("relationship_changes", [])
    if relationships:
        sections.append(
            "<h3>Relationship changes</h3>"
            + _table(
                [
                    {
                        "State": item.get("state", ""),
                        "Source": item.get("source", ""),
                        "Relation": item.get("relation", ""),
                        "Target": item.get("target", ""),
                    }
                    for item in relationships
                ]
            )
        )
    warnings = data.get("warnings", [])
    if warnings:
        sections.append(
            "<h3>Comparison warnings</h3><ul>"
            + "".join(f"<li>{html.escape(str(item))}</li>" for item in warnings)
            + "</ul>"
        )
    sections.append(
        '<p class="sub">Graph comparison describes changes between two evidence '
        "snapshots. It is not proof of leakage, remediation or causality.</p></div>"
    )
    return "".join(sections)


def _impact_section(data: dict) -> str:
    """Render measured dataset impact, escaping all dataset-derived values."""
    if not data:
        return ""

    rows = [
        ("Training rows", data.get("train_rows")),
        ("Test rows", data.get("test_rows")),
        (
            "Duplicate test rows",
            (
                f"{data.get('duplicate_test_rows', 0)} "
                f"({data.get('duplicate_test_pct', 0):.2f}%)"
            ),
        ),
    ]

    group_column = data.get("group_column")
    if group_column:
        rows.extend(
            [
                ("Group column", group_column),
                ("Shared group values", data.get("shared_group_count", 0)),
                (
                    "Test rows in shared groups",
                    (
                        f"{data.get('shared_group_test_rows', 0)} "
                        f"({data.get('shared_group_test_pct', 0):.2f}%)"
                    ),
                ),
            ]
        )

    time_column = data.get("time_column")
    if time_column:
        temporal = data.get("temporal_overlap")
        temporal_label = (
            "Not measurable" if temporal is None else "Yes" if temporal else "No"
        )
        rows.extend(
            [
                ("Time column", time_column),
                ("Temporal boundary overlap", temporal_label),
                (
                    "Latest training timestamp",
                    data.get("train_max_time") or "Unavailable",
                ),
                ("Earliest test timestamp", data.get("test_min_time") or "Unavailable"),
            ]
        )

    body = "".join(
        f"<tr><th>{html.escape(str(label))}</th><td>{html.escape(str(value))}</td></tr>"
        for label, value in rows
        if value is not None
    )
    return (
        "<h2>Dataset impact</h2>"
        f'<div class="card"><table>{body}</table>'
        '<p class="sub">These are measured split statistics, not estimates '
        "of model-performance loss or proof that every flagged feature row is affected.</p>"
        "</div>"
    )


