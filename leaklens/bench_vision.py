"""Generated, deterministic image-relationship benchmark (Phase 17 M2).

Two split folders of synthetic images are rendered from fixed seeds: exact
copies, re-encodes, resizes, small exposure shifts, a watermark, a 2-degree
rotation, mild crops, and hard negatives that share colours, backgrounds or
layout but not content. Threshold candidates are swept on the calibration
partition only; the holdout partition is evaluated once at the selected
threshold. Nothing is tuned against the holdout.

The corpus is generated by this module. It ships no third-party images and
makes no real-world accuracy claim: it is a regression guard for the documented
transformation envelope.

Usage: ``python -m leaklens.bench_vision [--write docs/VISION_BENCHMARK.md]``
"""

from __future__ import annotations

import hashlib
import json
import sys
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

from .images import (
    ImageBudget,
    analyze_images,
    cluster_signatures,
    dhash,
    file_digest,
    hamming,
)

CORPUS_VERSION = "1.0.0"
THRESHOLDS = tuple(range(13))
SUPPORTED_RECALL_FLOOR = 0.8
SIZE = 256
GRID = 6
CALIBRATION_SEEDS = (11, 12, 13, 14, 15)
HOLDOUT_SEEDS = (101, 102, 103, 104, 105)
SCALING_SIZES = (200, 1000, 4000)
PINNED_CORPUS_DIGEST = (
    "435b91e21a355723e061b9e3a8828c8dc9d554d939331f4890ab0da57c96d55a"
)


@dataclass(frozen=True, slots=True)
class Case:
    case_id: str
    partition: str
    family: str
    label: str
    seed: int


# label: exact | duplicate | unsupported | negative | known_collision
FAMILIES: dict[str, tuple[str, str]] = {
    "identical": ("exact", "byte-identical copy"),
    "jpeg": ("duplicate", "JPEG re-encode, quality 80"),
    "resize": ("duplicate", "resize to 75% then compare"),
    "brightness": ("duplicate", "brightness +12%"),
    "contrast": ("duplicate", "contrast +15%"),
    "watermark": ("duplicate", "30 px corner watermark"),
    "rotate2": ("duplicate", "2 degree rotation"),
    "crop97": ("duplicate", "3% border crop"),
    "crop95": ("duplicate", "5% border crop (threshold boundary)"),
    "crop92": ("unsupported", "8% border crop"),
    "crop75": ("unsupported", "25% border crop"),
    "letterbox": ("unsupported", "padded into a 320 px canvas"),
    "unrelated": ("negative", "unrelated base image"),
    "permuted": ("negative", "same coarse layout, rotated 180 degrees"),
    "shared_background": ("negative", "shared top half, different bottom half"),
    "flat_colour": ("negative", "different flat colours, no structure"),
    "crop50": ("negative", "half-image crop keeps different content"),
    "gradient_colour": (
        "known_collision",
        "smooth gradient, differently coloured disc",
    ),
}


def _pil():
    try:
        from PIL import Image, ImageDraw, ImageEnhance
    except ImportError:  # pragma: no cover - exercised by the skip test
        raise ImportError("image benchmark needs the 'images' extra (Pillow)") from None
    return Image, ImageDraw, ImageEnhance


def _coarse(seed: int):
    import numpy as np

    return np.random.default_rng(seed).integers(0, 256, (GRID, GRID, 3), dtype=np.uint8)


def _base(seed: int):
    Image, _, _ = _pil()
    return Image.fromarray(_coarse(seed)).resize((SIZE, SIZE), Image.Resampling.BICUBIC)


def _gradient(size: int = SIZE):
    import numpy as np

    line = np.linspace(0, 255, size)
    return np.stack([np.tile(line, (size, 1))] * 3, axis=-1).astype(np.uint8)


def _pair(seed: int, family: str):
    """Return ``(train image, test image, test suffix)`` for one family."""
    Image, ImageDraw, ImageEnhance = _pil()
    base = _base(seed)
    if family == "identical":
        return base, base, ".png"
    if family == "jpeg":
        return base, base, ".jpg"
    if family == "resize":
        return base, base.resize((192, 192), Image.Resampling.LANCZOS), ".png"
    if family == "brightness":
        return base, ImageEnhance.Brightness(base).enhance(1.12), ".png"
    if family == "contrast":
        return base, ImageEnhance.Contrast(base).enhance(1.15), ".png"
    if family == "watermark":
        marked = base.copy()
        ImageDraw.Draw(marked).rectangle((5, 5, 34, 34), fill=(255, 255, 255))
        return base, marked, ".png"
    if family == "rotate2":
        return base, base.rotate(2, resample=Image.Resampling.BICUBIC), ".png"
    if family.startswith("crop"):
        border = {"crop97": 4, "crop95": 6, "crop92": 10, "crop75": 32, "crop50": 64}
        inset = border[family]
        return base, base.crop((inset, inset, SIZE - inset, SIZE - inset)), ".png"
    if family == "letterbox":
        padded = Image.new("RGB", (320, 320), (127, 127, 127))
        padded.paste(base, (32, 32))
        return base, padded, ".png"
    if family == "unrelated":
        return base, _base(seed + 1000), ".png"
    if family == "permuted":
        import numpy as np

        return (
            base,
            Image.fromarray(np.rot90(_coarse(seed), 2)).resize(
                (SIZE, SIZE), Image.Resampling.BICUBIC
            ),
            ".png",
        )
    if family == "shared_background":
        import numpy as np

        first, second = _coarse(seed), _coarse(seed)
        first[: GRID // 2] = 128
        second[: GRID // 2] = 128
        second[GRID // 2 :] = np.random.default_rng(seed + 7).integers(
            0, 256, (GRID // 2, GRID, 3), dtype=np.uint8
        )
        resize = Image.Resampling.BICUBIC
        return (
            Image.fromarray(first).resize((SIZE, SIZE), resize),
            Image.fromarray(second).resize((SIZE, SIZE), resize),
            ".png",
        )
    if family == "flat_colour":
        return (
            Image.new("RGB", (SIZE, SIZE), (220, 30, 30)),
            Image.new("RGB", (SIZE, SIZE), (30, 30, 220)),
            ".png",
        )
    if family == "gradient_colour":
        frames = []
        for colour in ((200, 40, 40), (40, 40, 200)):
            frame = Image.fromarray(_gradient())
            ImageDraw.Draw(frame).ellipse((60, 60, 200, 200), fill=colour)
            frames.append(frame)
        return frames[0], frames[1], ".png"
    raise KeyError(f"unknown family: {family}")


def corpus() -> list[Case]:
    """Every case, calibration before holdout, family order preserved."""
    cases: list[Case] = []
    for partition, seeds in (
        ("calibration", CALIBRATION_SEEDS),
        ("holdout", HOLDOUT_SEEDS),
    ):
        for seed in seeds:
            for family in FAMILIES:
                label = FAMILIES[family][0]
                cases.append(
                    Case(f"{partition}-{family}-{seed}", partition, family, label, seed)
                )
    return cases


def corpus_digest(cases: list[Case]) -> str:
    """SHA-256 over the canonical case table; pixels are not part of it."""
    payload = json.dumps(
        [
            {
                "case_id": case.case_id,
                "partition": case.partition,
                "family": case.family,
                "label": case.label,
                "seed": case.seed,
            }
            for case in sorted(cases, key=lambda item: item.case_id)
        ],
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(f"{CORPUS_VERSION}\n{payload}".encode()).hexdigest()


def _sign(root: Path, case: Case) -> dict:
    """Render one case through the real intake and record both relationships."""
    train_image, test_image, suffix = _pair(case.seed, case.family)
    train_path = root / f"{case.case_id}-train.png"
    test_path = root / f"{case.case_id}-test{suffix}"
    train_image.save(train_path)
    test_image.save(test_path, format="JPEG" if suffix == ".jpg" else None)
    budget = ImageBudget()
    return {
        "case": case,
        "train_hash": dhash(train_path, budget=budget),
        "test_hash": dhash(test_path, budget=budget),
        "train_digest": file_digest(train_path),
        "test_digest": file_digest(test_path),
    }


def _exact(facts: dict) -> bool:
    return facts["train_digest"] == facts["test_digest"]


def _perceptual(facts: dict, threshold: int) -> bool:
    return (
        hamming(facts["train_hash"], 0) not in (0, 64)
        and hamming(facts["test_hash"], 0) not in (0, 64)
        and hamming(facts["train_hash"], facts["test_hash"]) <= threshold
    )


def _score(rows: list[dict], threshold: int) -> dict:
    buckets = {
        "exact": [],
        "duplicate": [],
        "unsupported": [],
        "negative": [],
        "known_collision": [],
    }
    for facts in rows:
        buckets[facts["case"].label].append(facts)
    duplicates = buckets["duplicate"]
    negatives = buckets["negative"]
    return {
        "threshold": threshold,
        "supported_recall": (
            sum(_perceptual(f, threshold) for f in duplicates) / len(duplicates)
            if duplicates
            else 1.0
        ),
        "unsupported_recall": (
            sum(_perceptual(f, threshold) for f in buckets["unsupported"])
            / len(buckets["unsupported"])
            if buckets["unsupported"]
            else 1.0
        ),
        "negative_merges": sum(_perceptual(f, threshold) for f in negatives),
        "negatives": len(negatives),
        "known_collisions": sum(
            _perceptual(f, threshold) for f in buckets["known_collision"]
        ),
        "known_collision_cases": len(buckets["known_collision"]),
    }


def select_threshold(sweep: list[dict]) -> int:
    """Best supported recall with zero negative merges; smallest distance wins."""
    eligible = [row for row in sweep if row["negative_merges"] == 0]
    if not eligible:  # no threshold is safe; report the least bad
        return min(sweep, key=lambda row: (row["negative_merges"], row["threshold"]))[
            "threshold"
        ]
    return min(
        eligible,
        key=lambda row: (-row["supported_recall"], row["threshold"]),
    )["threshold"]


def _families(rows: list[dict], threshold: int, partition: str) -> list[dict]:
    names = list(FAMILIES)
    out = []
    for family in names:
        subset = [facts for facts in rows if facts["case"].family == family]
        if not subset:
            continue
        out.append(
            {
                "family": family,
                "label": FAMILIES[family][0],
                "description": FAMILIES[family][1],
                "partition": partition,
                "detected": sum(_perceptual(f, threshold) for f in subset),
                "exact": sum(_exact(f) for f in subset),
                "cases": len(subset),
            }
        )
    return out


def _cluster_check(threshold: int) -> dict:
    """One mixed collection: each base and its resize copy, plus unrelated noise."""
    Image, _, _ = _pil()
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        train, test = root / "train", root / "test"
        train.mkdir()
        test.mkdir()
        expected = set()
        for seed in CALIBRATION_SEEDS:
            _base(seed).save(train / f"base-{seed}.png")
            _base(seed).resize((192, 192), Image.Resampling.LANCZOS).save(
                test / f"copy-{seed}.png"
            )
            expected.add(f"base-{seed}")
        for seed in (900, 901):
            _base(seed).save(train / f"noise-train-{seed}.png")
            _base(seed + 10).save(test / f"noise-test-{seed}.png")
        audit = analyze_images(train, test, threshold)
        false_merges: list[list[str]] = []
        found: set[str] = set()
        for cluster in audit.clusters:
            owners = {
                member.split(":")[1].split("-")[-1].split(".")[0]
                for member in cluster.members
            }
            if len(owners) > 1:
                false_merges.append(list(cluster.members))
            for owner in owners & {str(seed) for seed in CALIBRATION_SEEDS}:
                found.add(f"base-{owner}")
        return {
            "clusters": len(audit.clusters),
            "expected_pairs": len(expected),
            "found_pairs": len(found & expected),
            "false_merges": false_merges,
            "false_splits": sorted(expected - found),
            "members": sum(len(cluster.members) for cluster in audit.clusters),
        }


def _scaling(max_distance: int) -> list[dict]:
    """Clustering-stage cost by collection size; decoding is measured separately."""
    import numpy as np

    rng = np.random.default_rng(20261113)
    rows = []
    for size in SCALING_SIZES:
        hashes = {
            f"i{index}": int(rng.integers(0, 2**64, dtype=np.uint64))
            for index in range(size)
        }
        started = time.perf_counter()
        clusters, _exact, _unused = cluster_signatures(
            hashes, {}, {name: name for name in hashes}, {}, max_distance
        )
        rows.append(
            {
                "collection": "random",
                "images": size,
                "seconds": time.perf_counter() - started,
                "clusters": len(clusters),
            }
        )
    repeated = {f"i{index}": 0x5A5A5A5A5A5A5A5A for index in range(1000)}
    started = time.perf_counter()
    clusters, _exact, _unused = cluster_signatures(
        repeated, {}, {name: name for name in repeated}, {}, max_distance
    )
    rows.append(
        {
            "collection": "repetitive",
            "images": len(repeated),
            "seconds": time.perf_counter() - started,
            "clusters": len(clusters),
        }
    )
    return rows


def _decode_measure() -> dict:
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        for index in range(100):
            _base(index).save(root / f"i{index}.png")
        started = time.perf_counter()
        total = 0
        for index in range(100):
            total += dhash(root / f"i{index}.png", budget=ImageBudget())
        elapsed = time.perf_counter() - started
        return {
            "images": 100,
            "seconds": elapsed,
            "hashes": total,
            "images_per_second": 100 / elapsed if elapsed else 0.0,
        }


def evaluate(*, measure_runtime: bool = True) -> dict:
    cases = corpus()
    digest = corpus_digest(cases)
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        rows = [_sign(root, case) for case in cases]

    calibration = [f for f in rows if f["case"].partition == "calibration"]
    holdout = [f for f in rows if f["case"].partition == "holdout"]
    sweep = [_score(calibration, threshold) for threshold in THRESHOLDS]
    selected = select_threshold(sweep)
    calibration_score = next(row for row in sweep if row["threshold"] == selected)
    holdout_score = _score(holdout, selected)
    exact_calibration_cases = sum(
        1 for facts in calibration if facts["case"].label == "exact"
    )
    exact_holdout_cases = sum(1 for facts in holdout if facts["case"].label == "exact")
    exact_calibration = sum(
        1 for facts in calibration if facts["case"].label == "exact" and _exact(facts)
    )
    exact_holdout = sum(
        1 for facts in holdout if facts["case"].label == "exact" and _exact(facts)
    )
    clusters = _cluster_check(selected)
    misses = [
        f"{facts['case'].case_id}: distance "
        f"{hamming(facts['train_hash'], facts['test_hash'])}"
        for facts in calibration + holdout
        if facts["case"].label == "duplicate" and not _perceptual(facts, selected)
    ]
    result = {
        "corpus_version": CORPUS_VERSION,
        "corpus_digest": digest,
        "digest_pinned": digest == PINNED_CORPUS_DIGEST,
        "cases": len(cases),
        "calibration_cases": len(calibration),
        "holdout_cases": len(holdout),
        "exact_calibration_cases": exact_calibration_cases,
        "exact_holdout_cases": exact_holdout_cases,
        "exact_calibration": exact_calibration,
        "exact_holdout": exact_holdout,
        "thresholds": sweep,
        "selected": selected,
        "calibration": calibration_score,
        "holdout": holdout_score,
        "families": _families(calibration, selected, "calibration")
        + _families(holdout, selected, "holdout"),
        "clusters": clusters,
        "misses": misses,
        "scaling": _scaling(selected) if measure_runtime else [],
        "decode": _decode_measure() if measure_runtime else None,
    }
    result["ok"] = bool(
        result["digest_pinned"]
        and calibration_score["negative_merges"] == 0
        and holdout_score["negative_merges"] == 0
        and holdout_score["supported_recall"] >= SUPPORTED_RECALL_FLOOR
        and not clusters["false_merges"]
        and not clusters["false_splits"]
    )
    return result


def markdown(metrics: dict) -> str:
    rows = [
        "| Threshold | Supported recall | Unsupported recall | Negative merges | Known collisions |",
        "|---:|---:|---:|---:|---:|",
    ]
    for row in metrics["thresholds"]:
        rows.append(
            f"| {row['threshold']} | {row['supported_recall']:.2f} | "
            f"{row['unsupported_recall']:.2f} | {row['negative_merges']} | "
            f"{row['known_collisions']}/{row['known_collision_cases']} |"
        )
    families = [
        "| Partition | Family | Label | Cases | Detected | Exact |",
        "|---|---|---|---:|---:|---:|",
    ]
    for row in metrics["families"]:
        families.append(
            f"| {row['partition']} | {row['family']} | {row['label']} | "
            f"{row['cases']} | {row['detected']} | {row['exact']} |"
        )
    scaling = [
        "| Collection | Images | Seconds | Clusters |",
        "|---|---:|---:|---:|",
    ]
    for row in metrics["scaling"]:
        scaling.append(
            f"| {row['collection']} | {row['images']} | {row['seconds']:.3f} | "
            f"{row['clusters']} |"
        )
    decode = metrics["decode"]
    decode_rows = (
        "not measured"
        if decode is None
        else (
            f"{decode['images']} images in {decode['seconds']:.3f} s "
            f"({decode['images_per_second']:.1f} images/s)"
        )
    )
    misses = "\n".join(f"- {miss}" for miss in metrics["misses"]) or "- none"
    return (
        "# Vision benchmark (Phase 17 M2)\n\n"
        "Generated, deterministic image relationships for the Phase 17 M2 "
        "clustering contract. The corpus is produced by `leaklens.bench_vision`; "
        "no third-party image ships and no real-world accuracy is claimed. "
        "Threshold selection uses the calibration partition only; the holdout "
        "partition is scored once at the selected threshold.\n\n"
        f"Corpus version `{metrics['corpus_version']}`, "
        f"{metrics['cases']} cases "
        f"({metrics['calibration_cases']} calibration, "
        f"{metrics['holdout_cases']} holdout), digest "
        f"`{metrics['corpus_digest']}`.\n\n"
        "## Threshold sweep (calibration only)\n\n" + "\n".join(rows) + "\n\n"
        f"Selected threshold: **{metrics['selected']} bits** "
        "(best supported recall with zero negative merges; smaller distance on a tie).\n\n"
        "## Selected-threshold results\n\n"
        "| Partition | Supported recall | Unsupported recall | Negative merges | Known collisions | Exact |\n"
        "|---|---:|---:|---:|---:|---:|\n"
        f"| Calibration | {metrics['calibration']['supported_recall']:.2f} | "
        f"{metrics['calibration']['unsupported_recall']:.2f} | "
        f"{metrics['calibration']['negative_merges']} | "
        f"{metrics['calibration']['known_collisions']}/"
        f"{metrics['calibration']['known_collision_cases']} | "
        f"{metrics['exact_calibration']}/{metrics['exact_calibration_cases']} |\n"
        f"| Holdout | {metrics['holdout']['supported_recall']:.2f} | "
        f"{metrics['holdout']['unsupported_recall']:.2f} | "
        f"{metrics['holdout']['negative_merges']} | "
        f"{metrics['holdout']['known_collisions']}/"
        f"{metrics['holdout']['known_collision_cases']} | "
        f"{metrics['exact_holdout']}/{metrics['exact_holdout_cases']} |\n\n"
        "## Per-family results\n\n" + "\n".join(families) + "\n\n"
        "## Clustering (calibration collection)\n\n"
        "| Metric | Value |\n|---|---:|\n"
        f"| Clusters | {metrics['clusters']['clusters']} |\n"
        f"| Expected pairs | {metrics['clusters']['expected_pairs']} |\n"
        f"| Found pairs | {metrics['clusters']['found_pairs']} |\n"
        f"| False merges | {len(metrics['clusters']['false_merges'])} |\n"
        f"| False splits | {len(metrics['clusters']['false_splits'])} |\n\n"
        "## Scaling and decode (clustering stage)\n\n" + "\n".join(scaling) + "\n\n"
        f"Decode throughput: {decode_rows}. Runtime is runner-dependent and is "
        "recorded, not gated.\n\n"
        "## Misses\n\n" + misses + "\n\n"
        "## Method and limits\n\n"
        "- Hashes: 8x8 difference hash (64 bits), computed through the M-S5 "
        "decode budgets; every case is rendered from a fixed seed.\n"
        "- Exact: byte-identical files only, by SHA-256 of the file bytes.\n"
        "- Perceptual: Hamming distance at or below the selected threshold, "
        "excluding uniform hashes (all-zero or all-one) from clusters.\n"
        "- Clusters: connected components over direct comparisons; a cluster "
        "member is not necessarily within the threshold of every other member.\n"
        "- Negatives: unrelated images, 180-degree layout rotation, a shared "
        "background with different content, different flat colours and a "
        "half-image crop. A smooth gradient with a colour-only difference is "
        "counted as a known collision, not as a passing negative: dHash is "
        "grayscale and ignores colour.\n"
        "- Crops beyond 5% and letterboxing are reported as unsupported, not as "
        "passing positives: the threshold does not claim them.\n"
        "- Synthetic structured images are easier than real photographs; these "
        "numbers are a regression guard, not a real-world precision/recall claim.\n"
    )


def main(argv=None) -> int:
    argv = sys.argv[1:] if argv is None else list(argv)
    target = None
    if "--write" in argv:
        index = argv.index("--write")
        try:
            target = Path(argv[index + 1])
        except IndexError:
            raise SystemExit("--write needs a path") from None
    try:
        metrics = evaluate()
    except ImportError as exc:
        print(f"vision benchmark skipped: {exc}")
        return 0
    for row in metrics["thresholds"]:
        print(
            f"threshold {row['threshold']:2d}: supported recall "
            f"{row['supported_recall']:.2f}, unsupported "
            f"{row['unsupported_recall']:.2f}, negative merges "
            f"{row['negative_merges']}, known collisions "
            f"{row['known_collisions']}/{row['known_collision_cases']}"
        )
    print(
        f"selected threshold {metrics['selected']}; holdout supported recall "
        f"{metrics['holdout']['supported_recall']:.2f}, negative merges "
        f"{metrics['holdout']['negative_merges']}"
    )
    print(f"corpus {metrics['corpus_version']} digest {metrics['corpus_digest']}")
    clusters = metrics["clusters"]
    print(
        f"clusters: {clusters['clusters']} for {clusters['expected_pairs']} "
        f"expected pairs, false merges {len(clusters['false_merges'])}, "
        f"false splits {len(clusters['false_splits'])}"
    )
    for miss in metrics["misses"]:
        print(f"miss: {miss}")
    for row in metrics["scaling"]:
        print(
            f"scaling {row['collection']} {row['images']}: "
            f"{row['seconds']:.3f}s, {row['clusters']} cluster(s)"
        )
    if metrics["decode"] is not None:
        decode = metrics["decode"]
        print(
            f"decode: {decode['images']} images in {decode['seconds']:.3f}s "
            f"({decode['images_per_second']:.1f}/s)"
        )
    if target:
        target.write_text(markdown(metrics), encoding="utf-8")
        print(f"Wrote {target}")
    return 0 if metrics["ok"] else 1


if __name__ == "__main__":  # pragma: no cover - CLI entry point
    raise SystemExit(main())
